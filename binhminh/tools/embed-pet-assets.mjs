// Embeds the 3D pet models and pet voice clips as base64 TypeScript modules.
// Usage: node binhminh/tools/embed-pet-assets.mjs <glb-dir> <sound-dir>
//   <glb-dir>: self-contained Kenney Cube Pets GLBs (cat, dog, fox, bunny, panda, penguin)
//   <sound-dir>: clips from binhminh/tools/build-pet-sounds.sh
// Why base64 modules: Chromium's fetch rejects file:// URLs, which is how the packaged renderer
// loads, while an imported string works the same in dev, the packaged app and Vitest.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, basename } from 'node:path'

const [glbDir, soundDir] = process.argv.slice(2)
const root = 'src/renderer/src/components/binhminh-corner'
const header = '// Generated by binhminh/tools/embed-pet-assets.mjs from CC0 assets; do not edit.\n'

const MODELS = {
  cat: 'cat',
  dog: 'dog',
  fox: 'fox',
  rabbit: 'bunny',
  panda: 'panda',
  penguin: 'penguin'
}
mkdirSync(join(root, 'pet3d/models'), { recursive: true })
for (const [species, file] of Object.entries(MODELS)) {
  const b64 = readFileSync(join(glbDir, `${file}.glb`)).toString('base64')
  writeFileSync(join(root, 'pet3d/models', `${species}.ts`), `${header}export default '${b64}'\n`)
  console.log(`model ${species}: ${(b64.length / 1024).toFixed(0)} KB base64`)
}

const sounds = {}
for (const name of readdirSync(soundDir)
  .filter((f) => f.endsWith('.ogg'))
  .sort()) {
  const species = basename(name, '.ogg').replace(/-\d+$/, '')
  const b64 = readFileSync(join(soundDir, name)).toString('base64')
  ;(sounds[species] ??= []).push(`data:audio/ogg;base64,${b64}`)
}
const body = Object.entries(sounds)
  .map(([species, list]) => `  ${species}: [\n${list.map((u) => `    '${u}'`).join(',\n')}\n  ]`)
  .join(',\n')
writeFileSync(
  join(root, 'pet-sound-data.ts'),
  `${header}export const PET_SOUND_DATA: Readonly<Record<string, readonly string[]>> = {\n${body}\n}\n`
)
console.log(`sounds: ${Object.keys(sounds).join(', ')}`)
